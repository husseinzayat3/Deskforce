import fs from 'fs';
import path from 'path';
import { createZip, ZipEntry } from '../zip';
import { DATA_DIR, PROJECTS_DIR } from './paths';
import { Attachment } from '../types';

// The `turbopackIgnore` comments below mark paths inside the data folder, which is chosen at
// run time: without them the bundler would try to package the whole checkout with the server.

/** Caches and build output: never part of what the agents wrote. */
const IGNORED_DIRS = new Set(['.dart_tool', 'build', 'node_modules', '.git', '.idea', '.gradle']);

/** Left out of a download: caches and build output that the tools regenerate. */
const DOWNLOAD_IGNORED = new Set(['.dart_tool', 'build', 'node_modules', '.git', '.idea', '.gradle', 'Pods', 'ephemeral', '.scaffolded', '.DS_Store']);

/** Generated or bookkeeping files whose contents would only waste an agent's context. */
const NO_CONTENT_FILES = new Set(['pubspec.lock', 'package-lock.json', '.gitignore', 'analysis_options.yaml']);
/** Reports and transcripts the office writes itself. */
const OFFICE_FILE = /^(REPORT(-\d+)?\.md|docs\/task-transcript(-\d+)?\.md)$/;
/** Larger files are listed for agents by name only. */
const MAX_CONTENT_BYTES = 20_000;

/** Project folder names are generated by the office but re-validated wherever they are used as a path. */
export const safeProject = (project: unknown): string | null => {
  if (typeof project !== 'string') return null;
  return /^[a-z0-9][a-z0-9-]{0,60}$/.test(project) ? project : null;
};

const projectDirOf = (project: string) => {
  const safe = safeProject(project);
  if (!safe) throw new Error(`Invalid project: ${project}`);
  return path.join(/* turbopackIgnore: true */ PROJECTS_DIR, safe);
};

/**
 * Resolve a relative path inside the project dir.
 * Rejects absolute paths and anything that escapes the sandbox.
 */
const resolveInside = (baseDir: string, relPath: string): string | null => {
  const cleaned = relPath.trim().replace(/^[`'"]+|[`'"]+$/g, '').replace(/\\/g, '/').replace(/^\.?\/+/, '');
  if (!cleaned || path.isAbsolute(cleaned) || cleaned.split('/').includes('..')) return null;
  const full = path.resolve(baseDir, cleaned);
  return full.startsWith(baseDir + path.sep) ? full : null;
};

/** LLMs often wrap file bodies in markdown code fences — strip them. */
const stripFences = (content: string) => {
  const trimmed = content.replace(/^\s*\n/, '').replace(/\s+$/, '');
  const fenced = trimmed.match(/^```[\w+-]*\s*\n([\s\S]*?)\n```$/);
  return (fenced ? fenced[1] : trimmed) + '\n';
};

const listDir = (dir: string, base = dir, out: string[] = []): string[] => {
  if (!fs.existsSync(/* turbopackIgnore: true */ dir)) return out;
  for (const entry of fs.readdirSync(/* turbopackIgnore: true */ dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') && entry.name !== '.gitignore') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!IGNORED_DIRS.has(entry.name)) listDir(full, base, out);
    } else {
      out.push(path.relative(base, full));
    }
  }
  return out.sort();
};

/** Absolute path of a project's folder. Throws on an invalid name. */
export const projectPath = (project: string) => projectDirOf(project);

export const projectExists = (project: string) => fs.existsSync(/* turbopackIgnore: true */ projectDirOf(project));

/** The project's own files (caches left out), relative to the project. */
export const listProjectFiles = (project: string) => listDir(projectDirOf(project));

/** Text contents of the project's own files, keyed by relative path. */
export const readProjectContents = (project: string, files = listProjectFiles(project)) => {
  const projectDir = projectDirOf(project);
  const contents: Record<string, string> = {};
  for (const file of files) {
    if (NO_CONTENT_FILES.has(file) || OFFICE_FILE.test(file) || file.endsWith('.iml')) continue;
    const full = path.join(/* turbopackIgnore: true */ projectDir, file);
    if (fs.statSync(/* turbopackIgnore: true */ full).size > MAX_CONTENT_BYTES) continue;
    const data = fs.readFileSync(/* turbopackIgnore: true */ full);
    if (data.includes(0)) continue; // binary
    contents[file] = data.toString('utf-8');
  }
  return contents;
};

/** Writes a file inside the project and returns its project-relative path. Throws on a path that escapes it. */
export const writeProjectFile = (project: string, filename: string, content: string) => {
  const projectDir = projectDirOf(project);
  fs.mkdirSync(/* turbopackIgnore: true */ projectDir, { recursive: true });

  const filePath = resolveInside(projectDir, filename);
  if (!filePath) throw new Error(`Unsafe path: ${filename}`);

  fs.mkdirSync(/* turbopackIgnore: true */ path.dirname(filePath), { recursive: true });
  fs.writeFileSync(/* turbopackIgnore: true */ filePath, stripFences(content), 'utf-8');
  return path.relative(projectDir, filePath);
};

/** Writes raw bytes into the project (attachments may be images or other binary files). */
const writeProjectBytes = (project: string, filename: string, data: Buffer) => {
  const projectDir = projectDirOf(project);
  const filePath = resolveInside(projectDir, filename);
  if (!filePath) throw new Error(`Unsafe path: ${filename}`);
  fs.mkdirSync(/* turbopackIgnore: true */ path.dirname(filePath), { recursive: true });
  fs.writeFileSync(/* turbopackIgnore: true */ filePath, data);
  return path.relative(projectDir, filePath);
};

/** Removes one file of the project. Returns false when it did not exist. */
export const deleteProjectFile = (project: string, relPath: string) => {
  const filePath = resolveInside(projectDirOf(project), relPath);
  if (!filePath) throw new Error(`Unsafe path: ${relPath}`);
  if (!fs.existsSync(/* turbopackIgnore: true */ filePath) || !fs.statSync(/* turbopackIgnore: true */ filePath).isFile()) return false;
  fs.rmSync(/* turbopackIgnore: true */ filePath);
  return true;
};

export interface ProjectInfo {
  name: string;
  /** Files the agents wrote (caches and history left out). */
  files: number;
  /** When a file in it last changed. */
  updatedAt: number;
  canPreview: boolean;
}

/** Every project folder, most recently changed first. */
export const listProjects = (): ProjectInfo[] => {
  if (!fs.existsSync(/* turbopackIgnore: true */ PROJECTS_DIR)) return [];
  return fs.readdirSync(/* turbopackIgnore: true */ PROJECTS_DIR, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && safeProject(entry.name))
    .map(entry => {
      const dir = projectDirOf(entry.name);
      const files = listDir(dir);
      const updatedAt = files.reduce((latest, file) => {
        try {
          return Math.max(latest, fs.statSync(/* turbopackIgnore: true */ path.join(/* turbopackIgnore: true */ dir, file)).mtimeMs);
        } catch {
          return latest;
        }
      }, fs.statSync(/* turbopackIgnore: true */ dir).mtimeMs);
      return { name: entry.name, files: files.length, updatedAt: Math.round(updatedAt), canPreview: Boolean(previewEntry(entry.name)) };
    })
    .sort((a, b) => b.updatedAt - a.updatedAt);
};

/** Removes a project folder with everything in it, history included. */
export const deleteProject = (project: string) => {
  fs.rmSync(/* turbopackIgnore: true */ projectDirOf(project), { recursive: true, force: true });
};

// --- Attachments ------------------------------------------------------------------

/** Files given with a task wait here until the task has a project folder to put them in. */
const ATTACHMENTS_DIR = path.join(/* turbopackIgnore: true */ DATA_DIR, 'attachments');

export const ATTACHMENT_LIMITS = { files: 300, totalBytes: 8_000_000 };

/** Folders that are never worth importing with an attached folder. */
const SKIPPED_ON_IMPORT = /(^|\/)(node_modules|\.git|\.dart_tool|build|dist|\.next|\.idea|\.gradle|Pods|__pycache__|\.venv|venv|\.DS_Store)(\/|$)/;

const IMAGE_TYPES: Record<string, string> = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp' };
const MAX_IMAGES_FOR_MODEL = 4;
const MAX_IMAGE_BYTES = 3_500_000;

const stagingDir = (taskId: string) => {
  if (!/^[a-z0-9]+$/i.test(taskId)) throw new Error('Invalid task');
  return path.join(/* turbopackIgnore: true */ ATTACHMENTS_DIR, taskId);
};

/**
 * Keeps a task's attachments until its project exists. Single files will land in `inputs/`;
 * the files of an attached folder keep their layout at the top of the project.
 * Returns the paths they will have inside the project.
 */
export const stageAttachments = (taskId: string, attachments: Attachment[], asProjectFiles: boolean) => {
  const dir = stagingDir(taskId);
  const kept: string[] = [];
  let total = 0;

  // An attached folder arrives as "folder/…": its contents become the project, without that outer folder
  const tops = new Set(attachments.map(a => String(a.path || '').replace(/\\/g, '/').replace(/^\/+/, '').split('/')[0]));
  const stripTop = asProjectFiles && tops.size === 1 && attachments.every(a => String(a.path || '').includes('/'));

  for (const attachment of attachments.slice(0, ATTACHMENT_LIMITS.files)) {
    const whole = String(attachment.path || '').replace(/\\/g, '/').replace(/^\/+/, '');
    const clean = stripTop ? whole.split('/').slice(1).join('/') : whole;
    if (!clean || SKIPPED_ON_IMPORT.test(clean)) continue;
    const target = asProjectFiles ? clean : `inputs/${clean.split('/').pop()}`;
    const full = resolveInside(dir, target);
    if (!full) continue;

    const data = Buffer.from(String(attachment.data || ''), 'base64');
    total += data.length;
    if (total > ATTACHMENT_LIMITS.totalBytes) throw new Error(`Attachments are limited to ${ATTACHMENT_LIMITS.totalBytes / 1_000_000} MB in total.`);

    fs.mkdirSync(/* turbopackIgnore: true */ path.dirname(full), { recursive: true });
    fs.writeFileSync(/* turbopackIgnore: true */ full, data);
    kept.push(path.relative(dir, full));
  }
  return kept;
};

/** Moves a task's waiting attachments into its project. Returns the paths that were added. */
export const installAttachments = (taskId: string, project: string) => {
  const dir = stagingDir(taskId);
  if (!fs.existsSync(/* turbopackIgnore: true */ dir)) return [];
  const added: string[] = [];
  const walk = (current: string) => {
    for (const entry of fs.readdirSync(/* turbopackIgnore: true */ current, { withFileTypes: true })) {
      const full = path.join(/* turbopackIgnore: true */ current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) added.push(writeProjectBytes(project, path.relative(dir, full), fs.readFileSync(/* turbopackIgnore: true */ full)));
    }
  };
  walk(dir);
  fs.rmSync(/* turbopackIgnore: true */ dir, { recursive: true, force: true });
  return added;
};

export const discardAttachments = (taskId: string) => {
  fs.rmSync(/* turbopackIgnore: true */ stagingDir(taskId), { recursive: true, force: true });
};

/** The attached pictures in a form a model can look at (a few, and not huge ones). */
export const attachedImages = (project: string, attachments: string[] = []) => {
  const images: { mediaType: string; data: string }[] = [];
  for (const file of attachments) {
    const mediaType = IMAGE_TYPES[path.extname(file).toLowerCase()];
    if (!mediaType || images.length >= MAX_IMAGES_FOR_MODEL) continue;
    const data = readProjectFile(project, file)?.data;
    if (data && data.length <= MAX_IMAGE_BYTES) images.push({ mediaType, data: data.toString('base64') });
  }
  return images;
};

/** Largest file the file browser shows as text. */
const MAX_VIEW_BYTES = 500_000;

const MIME_TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8', '.htm': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8', '.mjs': 'text/javascript; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif', '.webp': 'image/webp',
  '.ico': 'image/x-icon', '.txt': 'text/plain; charset=utf-8', '.md': 'text/plain; charset=utf-8', '.wasm': 'application/wasm',
  '.woff': 'font/woff', '.woff2': 'font/woff2', '.ttf': 'font/ttf', '.map': 'application/json; charset=utf-8',
};

/** A file of the project as raw bytes with its media type, or null when it does not exist or lies outside the project. */
export const readProjectFile = (project: string, relPath: string) => {
  const filePath = resolveInside(projectDirOf(project), relPath);
  if (!filePath || !fs.existsSync(/* turbopackIgnore: true */ filePath) || !fs.statSync(/* turbopackIgnore: true */ filePath).isFile()) return null;
  return {
    data: fs.readFileSync(/* turbopackIgnore: true */ filePath),
    contentType: MIME_TYPES[path.extname(filePath).toLowerCase()] || 'application/octet-stream',
  };
};

/** A file of the project as text for the file browser. `text` is missing for binary or very large files. */
export const viewProjectFile = (project: string, relPath: string) => {
  const file = readProjectFile(project, relPath);
  if (!file) return null;
  const viewable = file.data.length <= MAX_VIEW_BYTES && !file.data.includes(0);
  return { size: file.data.length, text: viewable ? file.data.toString('utf-8') : undefined };
};

/** Pages a static preview can start from, in order of preference. */
const PREVIEW_ENTRIES = ['index.html', 'web/index.html', 'public/index.html', 'build/web/index.html', 'dist/index.html', 'src/index.html'];

/** Where a browser preview of the project starts, or undefined when it has no web page. */
export const previewEntry = (project: string) => {
  const dir = projectDirOf(project);
  return PREVIEW_ENTRIES.find(entry => fs.existsSync(/* turbopackIgnore: true */ path.join(/* turbopackIgnore: true */ dir, entry)));
};

const collectForDownload = (dir: string, prefix: string, out: ZipEntry[] = []): ZipEntry[] => {
  for (const entry of fs.readdirSync(/* turbopackIgnore: true */ dir, { withFileTypes: true })) {
    if (DOWNLOAD_IGNORED.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    const name = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) collectForDownload(full, name, out);
    else if (entry.isFile()) out.push({ name, data: fs.readFileSync(/* turbopackIgnore: true */ full), mode: fs.statSync(/* turbopackIgnore: true */ full).mode & 0o777 });
  }
  return out;
};

/** The whole project as a .zip. */
export const zipProject = (project: string) => createZip(collectForDownload(projectDirOf(project), project));
